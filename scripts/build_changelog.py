#!/usr/bin/env python3
"""Render the public changelog with standard-library Python; no browser scripts or build service."""
import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ('added', 'changed', 'fixed')
LABELS = {'development': 'Development history', 'internal': 'Internal testing', 'beta': 'Beta', 'stable': 'Public release'}

def require(condition, message):
    if not condition:
        raise ValueError(message)

def validate(data):
    require(set(data) == {'format', 'version', 'unreleased', 'releases'}, 'Unknown or missing public fields')
    require(data['format'] == 'becken.changelog' and type(data['version']) is int and data['version'] == 1, 'Unsupported changelog schema')
    require(set(data['unreleased']) == set(SECTIONS), 'Invalid Unreleased fields')
    require(type(data['releases']) is list and data['releases'], 'No versions found')
    versions = []
    for entry in [data['unreleased']] + data['releases']:
        for key in SECTIONS:
            require(type(entry[key]) is list and all(type(note) is str and note.strip() for note in entry[key]), 'Invalid change notes')
    for entry in data['releases']:
        require(set(entry) == {'version', 'title', 'channel', 'releasedOn', 'playNotes', *SECTIONS}, 'Unknown release fields')
        require(type(entry['version']) is str and re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', entry['version']), 'Invalid version')
        versions.append(tuple(map(int, entry['version'].split('.'))))
        require(type(entry['title']) is str and entry['title'].strip(), 'Missing title')
        require(entry['channel'] in LABELS, 'Unknown channel')
        if entry['channel'] == 'development':
            require(entry['releasedOn'] is None, 'Development history must not invent a release date')
        else:
            require(type(entry['releasedOn']) is str and date.fromisoformat(entry['releasedOn']).isoformat() == entry['releasedOn'], 'A release needs a verified date')
        require(type(entry['playNotes']) is str and 1 <= len(entry['playNotes'].strip()) <= 500, 'Invalid Play notes')
    require(versions == sorted(set(versions), reverse=True), 'Versions must be unique and newest first')
    return data

def sections(entry):
    rendered = []
    for key in SECTIONS:
        if entry[key]:
            items = ''.join(f'<li>{escape(note)}</li>' for note in entry[key])
            rendered.append(f'<section class="change-section"><h3>{key.title()}</h3><ul>{items}</ul></section>')
    return '\n'.join(rendered)

def render(data):
    validate(data)
    articles = []
    links = []
    if any(data['unreleased'][key] for key in SECTIONS):
        articles.append('<article class="release upcoming" id="unreleased" aria-labelledby="title-unreleased"><header><p class="release-meta"><span class="version-badge">Unreleased</span><span>In progress</span></p><h2 id="title-unreleased">What we’re working on</h2></header>' + sections(data['unreleased']) + '</article>')
        links.append('<a href="#unreleased">Unreleased</a>')
    for entry in data['releases']:
        version = entry['version']
        anchor = 'v' + version.replace('.', '-')
        links.append(f'<a href="#{anchor}">{version}</a>')
        timing = f'<time datetime="{escape(entry["releasedOn"], quote=True)}">{escape(entry["releasedOn"])}</time>' if entry['releasedOn'] else ''
        articles.append(f'<article class="release" id="{anchor}" aria-labelledby="title-{anchor}"><header><p class="release-meta"><span class="version-badge">{version}</span><span>{LABELS[entry["channel"]]}</span>{timing}</p><h2 id="title-{anchor}">{escape(entry["title"])}</h2></header>{sections(entry)}</article>')
    return '''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#081722">
  <title>Becken changelog — What’s new</title>
  <meta name="description" content="Features, improvements and fixes in Becken, the free offline Android lifting log. Browse the version history.">
  <link rel="canonical" href="https://becken.app/changelog/">
  <meta property="og:title" content="Becken changelog — What’s new">
  <meta property="og:description" content="Features, improvements and fixes, version by version.">
  <meta property="og:type" content="website">
  <meta property="og:url" content="https://becken.app/changelog/">
  <meta property="og:image" content="https://becken.app/assets/social.png">
  <link rel="icon" href="../assets/logo.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../styles.css">
</head>
<body>
  <!-- Generated by scripts/build_changelog.py from changelog/releases.json. -->
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header wrap">
    <a class="brand" href="../" aria-label="Becken home"><img src="../assets/logo.svg" width="42" height="42" alt=""><span>Becken</span></a>
    <nav aria-label="Main navigation"><a href="../#screenshots">The app</a><a href="./" aria-current="page">Changelog</a><a href="../terms/">Terms</a><a href="../privacy/">Privacy</a></nav>
  </header>
  <main id="main" class="history wrap">
    <div class="history-intro">
      <p class="eyebrow">ONE VERSION AT A TIME.</p>
      <h1>What’s new<br>in <em>Becken.</em></h1>
      <p class="intro">Features, improvements and fixes. Every step forward, in one place.</p>
      <p class="history-note">Becken is currently in private testing. Development entries describe the app’s history, not public availability. Dates are shown only for confirmed releases.</p>
    </div>
    <details class="version-index"><summary>Jump to a version</summary><nav aria-label="Version history">''' + ''.join(links) + '''</nav></details>
    <div class="release-list">''' + '\n'.join(articles) + '''</div>
    <p class="back-to-top"><a href="#main">Back to top ↑</a></p>
  </main>
  <footer class="site-footer wrap"><span class="footer-brand">Becken <span>Make the next rep count.</span></span><nav aria-label="Footer navigation"><a href="./" aria-current="page">Changelog</a><a href="../terms/">Terms of Service</a><a href="../privacy/">Privacy Policy</a></nav></footer>
</body>
</html>
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'changelog/releases.json').read_text())
    expected = render(data)
    path = ROOT / 'changelog/index.html'
    if args.write:
        path.write_text(expected)
    else:
        require(path.exists() and path.read_text() == expected, 'Changelog HTML is stale. Run python3 scripts/build_changelog.py --write')
    print(f'Changelog {"written" if args.write else "checked"}: {len(data["releases"])} versions')

if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError) as error:
        raise SystemExit(str(error)) from error
